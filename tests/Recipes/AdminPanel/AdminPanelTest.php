/** Everything docs/recipes/admin-panel.md claims, run against PostgreSQL. */
final class AdminPanelTest extends KernelTestCase
{
    use RestoresPhpHandlers;

    private EntityManagerInterface $em;

    protected static function getKernelClass(): string
    {
        return AdminPanelKernel::class;
    }

    protected function setUp(): void
    {
        $connection = PostgresTestCase::connect();
        $connection->execute('DROP TABLE IF EXISTS recipe_customer, fuzzphony_customers, fuzzphony_customers__vocab, fuzzphony_customers__next, fuzzphony_customers__changes CASCADE');
        $connection->execute(<<<'SQL'
            CREATE TABLE recipe_customer (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar NOT NULL, company varchar NOT NULL,
                city varchar NOT NULL, active boolean NOT NULL, created_at timestamp NOT NULL
            )
            SQL);

        self::bootKernel();
        $em = self::getContainer()->get('doctrine.orm.entity_manager');
        self::assertInstanceOf(EntityManagerInterface::class, $em);
        $this->em = $em;
    }

    protected function tearDown(): void
    {
        // the tables of this recipe must not outlive it: a trigger on recipe_customer would be counted by other suites
        PostgresTestCase::connect()->execute('DROP TABLE IF EXISTS recipe_customer, fuzzphony_customers, fuzzphony_customers__vocab, fuzzphony_customers__next, fuzzphony_customers__changes, fuzzphony_customers_live, fuzzphony_customers_live__vocab CASCADE');
        parent::tearDown();
    }

    /** The first reindex, as the recipe says: schema, then reindex. The rows were there before the index existed. */
    private function firstReindex(): ApplicationTester
    {
        $connection = PostgresTestCase::connect();
        foreach ([
            ['Jonathan Smith', 'Acme Tools', 'Boston', 'true', '2025-06-01'],
            ['Joan Smythe', 'Globex', 'Denver', 'true', '2026-03-05'],
            ['Jon Smith', 'Smith Holdings', 'Austin', 'false', '2026-01-10'],
            ['Maria Garcia', 'Acme Tools', 'Boston', 'true', '2026-02-14'],
        ] as [$name, $company, $city, $active, $created]) {
            $connection->execute('INSERT INTO recipe_customer (name, company, city, active, created_at) VALUES (:n, :co, :ci, :a, :cr)', ['n' => $name, 'co' => $company, 'ci' => $city, 'a' => $active, 'cr' => $created]);
        }

        $tester = $this->console();
        self::assertSame(0, $tester->run(['command' => 'fuzzphony:schema', '--apply' => true], ['decorated' => false]), $tester->getDisplay());
        self::assertSame(0, $tester->run(['command' => 'fuzzphony:reindex', 'index' => 'customers'], ['decorated' => false]), $tester->getDisplay());

        return $tester;
    }

    private function console(): ApplicationTester
    {
        $console = new Application(self::$kernel ?? throw new \LogicException('The kernel is booted in setUp().'));
        $console->setAutoExit(false);

        return new ApplicationTester($console);
    }

    private function fuzzphony(): Fuzzphony
    {
        $fuzzphony = self::getContainer()->get(Fuzzphony::class);
        self::assertInstanceOf(Fuzzphony::class, $fuzzphony);

        return $fuzzphony;
    }

    /** @return list<FilterInterface> the filters of Customer, in the order its attributes declare them */
    private function filters(?FilterInterface $search = null): array
    {
        $registry = new SingleManagerRegistry($this->em);
        $search ??= self::getContainer()->get('recipe.filter');
        self::assertInstanceOf(FilterInterface::class, $search);

        return [
            $search,
            new BooleanFilter($registry, properties: ['active' => null]),
            new OrderFilter($registry, properties: ['name' => null, 'createdAt' => null]),
        ];
    }

    /**
     * Applies the filters on the query API Platform builds for the collection (root alias "o"), then the page,
     * and returns the customers' names in the order the query gives them.
     *
     * @param array<string, mixed> $filters the query string of the request
     *
     * @return list<string>
     */
    private function collection(array $filters, int $page = 1, int $perPage = 25): array
    {
        return $this->collectionWith($this->filters(), $filters, $page, $perPage);
    }

    /**
     * @param list<FilterInterface> $chain
     * @param array<string, mixed>  $filters
     *
     * @return list<string>
     */
    private function collectionWith(array $chain, array $filters, int $page = 1, int $perPage = 25): array
    {
        $qb = $this->query($chain, $filters)->setFirstResult(($page - 1) * $perPage)->setMaxResults($perPage);

        $names = [];
        foreach (new Paginator($qb, false) as $customer) {
            self::assertInstanceOf(Customer::class, $customer);
            $names[] = $customer->name;
        }

        return $names;
    }

    /**
     * @param list<FilterInterface> $chain
     * @param array<string, mixed>  $filters
     */
    private function query(array $chain, array $filters): QueryBuilder
    {
        $qb = $this->em->getRepository(Customer::class)->createQueryBuilder('o');
        foreach ($chain as $filter) {
            $filter->apply($qb, new QueryNameGenerator(), Customer::class, null, ['filters' => $filters]);
        }

        return $qb;
    }

    public function testTheFirstReindexIndexesTheRowsThatWereThereBeforeTheIndex(): void
    {
        $tester = $this->firstReindex();

        self::assertStringContainsString('4 documents', $tester->getDisplay());
        RecipeOutput::assertShown(__DIR__ . '/expected/reindex.txt', $tester->getDisplay());

        $doctor = $this->console();
        self::assertSame(0, $doctor->run(['command' => 'fuzzphony:doctor'], ['decorated' => false]), $doctor->getDisplay());
        self::assertStringContainsString('Index "customers"', $doctor->getDisplay());
        self::assertSame(4, $this->fuzzphony()->in('customers')->query('')->get()->total);
    }

    public function testATypoStillFindsTheCustomerAndTheOrderIsTheRelevanceOrder(): void
    {
        $this->firstReindex();

        $found = $this->collection(['q' => 'smiht']);

        self::assertEqualsCanonicalizing(['Jon Smith', 'Jonathan Smith'], $found);
        $ranked = [];
        foreach ($this->fuzzphony()->in('customers')->query('smiht')->get()->ids() as $id) {
            $ranked[] = $this->em->getRepository(Customer::class)->find((int) $id)?->name;
        }
        self::assertSame($found, $ranked, 'the collection is in the order Fuzzphony ranks it');
    }

    public function testWhatTheRecipeShows(): void
    {
        $this->firstReindex();

        // region: requests
        // GET /api/customers?q=smiht            a typo still finds both Smiths (equally relevant: the tie goes to the lower id)
        self::assertEqualsCanonicalizing(['Jonathan Smith', 'Jon Smith'], $this->collection(['q' => 'smiht']));
        // GET /api/customers?q=smith            best match first: Jon Smith has the word in his name and in his company
        self::assertSame(['Jon Smith', 'Jonathan Smith'], $this->collection(['q' => 'smith']));
        // GET /api/customers?q=company:globex   the query syntax of the search box works too (field:value, "phrase", -word, a OR b, pre*)
        self::assertSame(['Joan Smythe'], $this->collection(['q' => 'company:globex']));
        // GET /api/customers?q=smith&active=true     your own filter narrows what the search found
        self::assertSame(['Jonathan Smith'], $this->collection(['q' => 'smith', 'active' => 'true']));
        // GET /api/customers?q=smith&order[createdAt]=asc   the relevance order wins over the column sort
        self::assertSame(['Jon Smith', 'Jonathan Smith'], $this->collection(['q' => 'smith', 'order' => ['createdAt' => 'asc']]));
        // GET /api/customers?order[createdAt]=desc          no search text: the collection is yours again
        self::assertSame(['Joan Smythe', 'Maria Garcia', 'Jon Smith', 'Jonathan Smith'], $this->collection(['order' => ['createdAt' => 'desc']]));
        // endregion
    }

    public function testWithoutSearchTextTheCollectionIsTheApplicationsOwn(): void
    {
        $this->firstReindex();

        self::assertSame(['Joan Smythe', 'Maria Garcia', 'Jon Smith', 'Jonathan Smith'], $this->collection(['order' => ['createdAt' => 'desc']]));
        self::assertCount(4, $this->collection(['q' => '   ']), 'a blank search text filters nothing');
    }

    public function testTheApplicationsOwnFiltersNarrowTheSearch(): void
    {
        $this->firstReindex();

        self::assertSame(['Jon Smith', 'Jonathan Smith'], $this->collection(['q' => 'smith']));
        self::assertSame(['Jonathan Smith'], $this->collection(['q' => 'smith', 'active' => 'true']));
        self::assertSame(['Jon Smith'], $this->collection(['q' => 'smith', 'active' => 'false']));
    }

    public function testAnEntityThatIsNotSearchableLeavesTheCollectionAlone(): void
    {
        $this->firstReindex();
        $qb = $this->em->getRepository(Customer::class)->createQueryBuilder('o');
        $before = $qb->getDQL();

        $this->filters()[0]->apply($qb, new QueryNameGenerator(), 'App\Entity\NotSearchable', null, ['filters' => ['q' => 'smith']]);

        self::assertSame($before, $qb->getDQL(), 'without #[Searchable] on the resource the filter does nothing, and ?q= filters nothing');
    }

    public function testASearchWithoutHitsIsAnEmptyCollection(): void
    {
        $this->firstReindex();

        self::assertSame([], $this->collection(['q' => 'nonexistentxyz']));
    }

    public function testRelevanceOrderWinsOverTheOrderFilterWhetherItRunsFirstOrLast(): void
    {
        $this->firstReindex();
        $sort = ['q' => 'smith', 'order' => ['createdAt' => 'asc']];

        // "Jonathan Smith" is the older customer, so the oldest first would list it first: the sort of the column does not win
        self::assertSame(['Jon Smith', 'Jonathan Smith'], $this->collection($sort));
        // declared after the order filter, the search filter replaces its ORDER BY: the same result
        /** @var list<Customer> $reversed */
        $reversed = $this->query(array_reverse($this->filters()), $sort)->getQuery()->getResult();
        self::assertSame(['Jon Smith', 'Jonathan Smith'], array_map(static fn(Customer $c): string => $c->name, $reversed));
    }

    public function testAFilterThatOnlyRestrictsLetsTheColumnSortWin(): void
    {
        $this->firstReindex();
        $chain = $this->filters(new SearchRestrictionFilter($this->fuzzphony()));

        self::assertSame(['Jonathan Smith', 'Jon Smith'], $this->collectionWith($chain, ['q' => 'smith', 'order' => ['createdAt' => 'asc']]));
        self::assertSame([], $this->collectionWith($chain, ['q' => 'nonexistentxyz']));
        self::assertCount(4, $this->collectionWith($chain, []));
    }

    public function testPagesFollowTheRelevanceOrderAndTheTotalIsWhatTheSearchFound(): void
    {
        $this->firstReindex();
        $all = $this->collection(['q' => 'smth']);
        self::assertCount(3, $all);

        self::assertSame(array_slice($all, 0, 2), $this->collection(['q' => 'smth'], 1, 2));
        self::assertSame(array_slice($all, 2), $this->collection(['q' => 'smth'], 2, 2));

        // API Platform counts with Doctrine's Paginator, with or without fetch-join: hydra:totalItems is the number of hits
        $qb = $this->query($this->filters(), ['q' => 'smth'])->setFirstResult(0)->setMaxResults(2);
        self::assertCount(3, new Paginator($qb, false));
        self::assertCount(3, new Paginator($qb, true));
    }

    public function testTheCollectionIsCappedAtMaxResultsBeforeTheOtherFiltersRun(): void
    {
        $this->firstReindex();
        $capped = $this->filters(new FuzzphonySearchFilter($this->fuzzphony(), maxResults: 1));

        self::assertCount(1, $this->collectionWith($capped, ['q' => 'smth']), 'the total is the cap, not the number of matches');
        // "Jonathan Smith" is an active customer the search finds, but it is not the best match, which is all the cap keeps
        self::assertSame([], $this->collectionWith($capped, ['q' => 'smith', 'active' => 'true']));
        self::assertSame(['Jonathan Smith'], $this->collection(['q' => 'smith', 'active' => 'true']), 'with the default cap of 500 it is found');
    }

    public function testTheSearchParameterCanBeRenamed(): void
    {
        $this->firstReindex();
        $renamed = new FuzzphonySearchFilter($this->fuzzphony(), parameterName: 'search');

        self::assertCount(2, $this->collectionWith($this->filters($renamed), ['search' => 'smiht']));
        self::assertCount(4, $this->collectionWith($this->filters($renamed), ['q' => 'smiht']), 'q is an ordinary parameter now');
        self::assertArrayHasKey('search', $renamed->getDescription(Customer::class));
    }

    public function testOrmSyncKeepsTheIndexFreshAfterFlushButNotAfterRawSql(): void
    {
        $this->firstReindex();
        $listener = self::getContainer()->get('recipe.orm_sync_listener');
        self::assertInstanceOf(OrmSyncListener::class, $listener);
        // DoctrineBundle does this for the service the Fuzzphony bundle tags; this kernel has no DoctrineBundle
        $this->em->getEventManager()->addEventListener(['postPersist', 'postUpdate', 'preRemove', 'postFlush'], $listener);

        $customer = new Customer('Ada Lovelace', 'Analytical Engines', 'London');
        $this->em->persist($customer);
        $this->em->flush();
        self::assertSame(['Ada Lovelace'], $this->collection(['q' => 'lovelace']), 'a new customer is searchable as soon as flush() returns');

        $customer->name = 'Ada Byron';
        $this->em->flush();
        self::assertSame(['Ada Byron'], $this->collection(['q' => 'byron']));
        self::assertSame([], $this->collection(['q' => 'lovelace']));

        PostgresTestCase::connect()->execute("UPDATE recipe_customer SET name = 'Grace Hopper' WHERE name = 'Ada Byron'");
        self::assertSame([], $this->collection(['q' => 'hopper']), 'a write that does not go through the entity manager is not seen in orm mode');
        $this->fuzzphony()->reindex('customers');
        $this->em->clear(); // the entity manager still holds the old name of the customer it loaded
        self::assertSame(['Grace Hopper'], $this->collection(['q' => 'hopper']), 'until the next reindex');

        $this->em->remove($this->em->getRepository(Customer::class)->findOneBy(['name' => 'Grace Hopper']) ?? throw new \LogicException('Grace Hopper was reindexed above.'));
        $this->em->flush();
        self::assertSame([], $this->collection(['q' => 'hopper']));
    }

    public function testTriggerSyncSeesEveryWriteAtOnce(): void
    {
        $this->firstReindex();
        $connection = PostgresTestCase::connect();
        $connection->execute('DROP TABLE IF EXISTS fuzzphony_customers_live, fuzzphony_customers_live__vocab CASCADE');
        $live = IndexDefinition::builder('customers_live')
            ->fromTable('recipe_customer')
            ->field('name', 'A', fuzzy: true)
            ->sync(SyncMode::Trigger)
            ->build();
        $fuzzphony = new Fuzzphony(new PostgresEngine($connection), new IndexRegistry([$live]));
        $fuzzphony->schema()->apply($connection);
        $fuzzphony->reindex('customers_live');

        $connection->execute("INSERT INTO recipe_customer (name, company, city, active, created_at) VALUES ('Linus Torvalds', 'Linux', 'Portland', true, now())");
        self::assertSame(1, $fuzzphony->in('customers_live')->query('torvalds')->get()->total, 'raw SQL, an import or another service: the trigger indexes it at once');
        $connection->execute("DELETE FROM recipe_customer WHERE name = 'Linus Torvalds'");
        self::assertSame(0, $fuzzphony->in('customers_live')->query('torvalds')->get()->total);
    }
}
